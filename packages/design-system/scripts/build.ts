/** Builds dist/tokens.css and dist/tokens.json from src/tokens.ts. Run: node scripts/build.ts */
import { writeFileSync, mkdirSync } from 'node:fs';
import { tokens, themes, type ColorRoles } from '../src/tokens.ts';

const kebab = (s: string) => s.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase());
const roles = (t: ColorRoles) => Object.entries(t).map(([k, v]) => `  --c-${kebab(k)}: ${v};`).join('\n');

const { type, space, radius, motion, layout, font, shadow } = tokens;
const scalar = [
  `  --font: ${font.family};`,
  `  --w-regular: ${font.weight.regular};`,
  `  --w-strong: ${font.weight.strong};`,
  ...Object.entries(type).map(([k, v]) => `  --fs-${k}: ${v.size}px;\n  --lh-${k}: ${v.line}px;` + ('tracking' in v ? `\n  --tr-${k}: ${v.tracking}em;` : '')),
  ...Object.entries(space).map(([k, v]) => `  --s-${k}: ${v}px;`),
  ...Object.entries(radius.tight).map(([k, v]) => `  --r-${k}: ${v}px;`),
  ...Object.entries(motion.duration).map(([k, v]) => `  --d-${k}: ${v}ms;`),
  ...Object.entries(motion.easing).map(([k, v]) => `  --e-${k}: ${v};`),
  `  --press-scale: ${motion.press.scale};`,
  ...Object.entries(layout).filter(([, v]) => typeof v === 'number').map(([k, v]) => `  --l-${kebab(k)}: ${v}px;`),
].join('\n');

const css = `/* Generated by scripts/build.ts — do not edit. Source: src/tokens.ts */
:root {
${scalar}
}
:root, :root[data-theme="light"] {
${roles(themes.light)}
  --shadow-popover: ${shadow.light.popover};
  --shadow-dialog: ${shadow.light.dialog};
  color-scheme: light;
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]):not([data-theme="oled"]) {
${roles(themes.dark)}
    --shadow-popover: ${shadow.dark.popover};
    --shadow-dialog: ${shadow.dark.dialog};
    color-scheme: dark;
  }
}
:root[data-theme="dark"] {
${roles(themes.dark)}
  --shadow-popover: ${shadow.dark.popover};
  --shadow-dialog: ${shadow.dark.dialog};
  color-scheme: dark;
}
:root[data-theme="oled"] {
${roles(themes.oled)}
  --shadow-popover: ${shadow.dark.popover};
  --shadow-dialog: ${shadow.dark.dialog};
  color-scheme: dark;
}
:root[data-radius="soft"] {
${Object.entries(radius.soft).map(([k, v]) => `  --r-${k}: ${v}px;`).join('\n')}
}
@media (prefers-reduced-motion: reduce) {
  :root { --d-instant: 0ms; --d-quick: 0ms; --d-base: 0ms; --d-slow: 0ms; --press-scale: 1; }
}
`;
mkdirSync(new URL('../dist/', import.meta.url), { recursive: true });
writeFileSync(new URL('../dist/tokens.css', import.meta.url), css);
writeFileSync(new URL('../dist/tokens.json', import.meta.url), JSON.stringify(tokens, null, 2));
console.log('tokens.css + tokens.json written');
